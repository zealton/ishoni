#!/usr/bin/env python3
"""Install the local Codex dispatcher adapter as a Linux user-systemd service (Python 3.8+).

Prerequisites that this installer never creates or starts: an existing Codex session UUID used as
the fixed dispatcher, a running local Codex app-server owned by this user and reachable through an
explicit `unix:///absolute/socket` URL, a durable Tailmsg receiver in the data home, and a user
systemd manager. The adapter code is copied into <home>/codex-local so the service never runs from
a plugin cache. --dry-run writes nothing and runs nothing; --no-start writes files and never calls
systemctl. Rollback restores one backup without deleting the inbox, queue or handled records.
"""
import sys

sys.dont_write_bytecode = True   # the installer may run from a plugin cache; keep it pristine

import argparse
import datetime
import json
import os
from pathlib import Path
import shutil
import stat
import subprocess
import uuid

from codex_queue_client import CodexAppError, unix_socket_path
from install_codex_bridge import FILES, atomic, check_queue_dispatcher, install_sources, merged_bridge_config

SOURCE = Path(__file__).resolve().parent
SERVICE = "tailmsg-codex-bridge.service"
RECEIVER_SERVICE = "tailmsg.service"
MANAGER = "systemd-user"
BACKUP_PREFIX = "codex-bridge-linux-"
BACKUP_NAMES = ("tailmsg-config.json", "bridge-config.json", "service.systemd", "bridge-installation.json") + \
    tuple("codex-local/" + name for name in FILES)


class InstallError(RuntimeError):
    """A refusal; nothing has been written when raised before the backup is created."""


def unit_dir():
    """Where `systemctl --user` looks for user units ($XDG_CONFIG_HOME only when absolute)."""
    base = os.environ.get("XDG_CONFIG_HOME", "")
    base = Path(base) if os.path.isabs(base) else Path.home() / ".config"
    return base / "systemd" / "user"


def unit_quote(value, expand_dollar=True):
    """One literal argument for a unit file: C-style escapes inside quotes, %% for specifiers and,
    where systemd expands variables (ExecStart=), $$ for a literal dollar."""
    if any(ord(char) < 32 or char == "\x7f" for char in value):
        raise InstallError("paths must not contain control characters: %r" % value)
    value = value.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    if expand_dollar:
        value = value.replace("$", "$$")
    return '"' + value + '"'


def unit_contents(python, script, config_path, codex_path):
    path = ["/usr/local/bin", "/usr/bin", "/bin"]
    cli_dir = os.path.dirname(codex_path)
    if ":" not in cli_dir and cli_dir not in path:
        path.insert(0, cli_dir)   # script launchers such as `#!/usr/bin/env node` live beside their runtime
    argv = [python, str(script), "--config", str(config_path), "daemon"]
    return ("# Generated by install_codex_bridge_linux.py; manage it with `ishoni codex-bridge`.\n"
            "[Unit]\nDescription=Tailmsg Codex dispatcher bridge (Ishoni)\n\n"
            "[Service]\nType=simple\n"
            "ExecStart=" + " ".join(unit_quote(arg) for arg in argv) + "\n"
            "Environment=" + unit_quote("PATH=" + ":".join(path), expand_dollar=False) + "\n"
            "UMask=0077\nRestart=always\nRestartSec=5\n\n"
            "[Install]\nWantedBy=default.target\n").encode("utf-8")


def systemctl(*args):
    try:
        return subprocess.run(["systemctl", "--user"] + list(args), stdin=subprocess.DEVNULL,
                              capture_output=True, text=True, timeout=60, check=False)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise InstallError("systemctl --user %s could not run: %s" % (" ".join(args), exc)) from exc


def require_manager():
    """Read-only check, before any write, that the user's systemd manager answers."""
    result = systemctl("show-environment")
    if result.returncode != 0:
        raise InstallError("the user systemd manager is not reachable (%s). Log in with a user session or enable "
                           "lingering (and set XDG_RUNTIME_DIR), or use --no-start to write files only"
                           % ((result.stderr or "").strip()[-200:] or "exit %d" % result.returncode))


def service_state():
    return {"active": systemctl("is-active", "--quiet", SERVICE).returncode == 0,
            "enabled": systemctl("is-enabled", "--quiet", SERVICE).returncode == 0}


def run_checked(*args):
    result = systemctl(*args)
    if result.returncode != 0:
        raise InstallError("systemctl --user %s failed: %s" % (" ".join(args), (result.stderr or "").strip()[-300:]))


def regular_or_absent(path):
    if os.path.lexists(str(path)) and (path.is_symlink() or not path.is_file()):
        raise InstallError("refusing to replace %s: it is not a regular file (symlinks are not followed)" % path)


def directory_or_absent(path):
    if os.path.lexists(str(path)) and (path.is_symlink() or not path.is_dir()):
        raise InstallError("refusing to use %s: it must be a real directory, not a symlink or file" % path)


def read_json_object(path, what):
    regular_or_absent(path)
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise InstallError("cannot read %s %s: %s" % (what, path, exc)) from exc
    if not isinstance(value, dict):
        raise InstallError("%s %s must contain a JSON object" % (what, path))
    return value


def owned_directory(path, what):
    try:
        info = os.stat(str(path))
    except OSError as exc:
        raise InstallError("%s %s does not exist" % (what, path)) from exc
    if not stat.S_ISDIR(info.st_mode) or info.st_uid != os.getuid():
        raise InstallError("%s %s must be a directory owned by this user" % (what, path))


def require_unit_owner(unit_path, config_path):
    """The unit name is per user, not per data home: never let one home take over another's bridge."""
    if unit_path.is_file() and unit_quote(str(config_path)).encode("utf-8") not in unit_path.read_bytes():
        raise InstallError("%s belongs to a bridge for another data home or configuration; roll that "
                           "installation back first" % unit_path)


def layout(home):
    """{name in backup: target path} for everything the installer may write."""
    target = home / "codex-local"
    paths = {"tailmsg-config.json": home / "config.json", "bridge-config.json": home / "codex-bridge.json",
             "service.systemd": unit_dir() / SERVICE,
             "bridge-installation.json": home / "codex-bridge" / "installation.json"}
    paths.update({"codex-local/" + name: target / name for name in FILES})
    return paths


def resolve_home(value):
    home = Path(value).expanduser()
    if not home.is_absolute() or any(ord(char) < 32 for char in str(home)):
        raise InstallError("--tailmsg-home must be an absolute path")
    return home.resolve()


def plan_install(args):
    """Validate everything and describe the change. Reads only; never writes or calls systemctl."""
    try:
        thread_id = str(uuid.UUID(args.thread_id))
    except ValueError as exc:
        raise InstallError("--thread-id must be the UUID of an existing Codex session") from exc
    if not args.codex_remote:
        raise InstallError("--codex-remote unix:///absolute/socket is required: the explicit socket of your "
                           "running local Codex app-server")
    try:
        socket_path = unix_socket_path(args.codex_remote)
    except CodexAppError as exc:
        raise InstallError(str(exc)) from exc
    home = resolve_home(args.tailmsg_home)
    notes = []
    for name in FILES:
        if not (SOURCE / name).is_file():
            raise InstallError("missing adapter source: " + name)
    if not (home / "tailmsg.py").is_file():
        raise InstallError("install the Tailmsg receiver runtime first (%s is missing)" % (home / "tailmsg.py"))
    paths = layout(home)
    for path in paths.values():
        regular_or_absent(path)
    for directory in (home / "codex-local", home / "codex-bridge", home / "backups"):
        directory_or_absent(directory)
    config_path = paths["bridge-config.json"]
    unit_path = paths["service.systemd"]
    require_unit_owner(unit_path, config_path)
    tailmsg_config = read_json_object(paths["tailmsg-config.json"], "Tailmsg config")
    agents = tailmsg_config.get("agents")
    if agents is not None and not isinstance(agents, dict):
        raise InstallError("config.json agents must be an object; fix it before installing")
    current = (agents or {}).get("codex")
    if current is not None and not isinstance(current, dict):
        raise InstallError("config.json agents.codex must be an object; fix it before installing")
    existing = read_json_object(config_path, "bridge config") if os.path.lexists(str(config_path)) else {}
    state = home / "codex-bridge"
    if existing.get("dispatcher_thread_id", thread_id) != thread_id:
        raise InstallError("the persistent dispatcher ID cannot be replaced by reinstalling; drain and review the "
                           "existing queue first")
    for key, expected in (("bridge_home", state), ("tailmsg_home", home)):
        if existing.get(key) and Path(existing[key]).expanduser().resolve() != expected:
            raise InstallError("the existing bridge config uses another %s; the queue location cannot be moved by "
                               "reinstalling" % key)
    try:
        check_queue_dispatcher(state / "bridge.sqlite3", thread_id)
    except RuntimeError as exc:
        raise InstallError(str(exc)) from exc
    # Pinned settings win over the ambient shell, so an upgrade run from another Codex session or account
    # never silently changes the runtime the bridge targets: explicit flag, then the existing config.
    codex_path = args.codex_path or existing.get("codex_path") or shutil.which("codex")
    if not codex_path:
        raise InstallError("no `codex` on PATH; pass --codex-path /absolute/path/to/codex")
    codex_path = os.path.abspath(os.path.expanduser(codex_path))   # not resolved: CLI updates move the target
    if not os.path.isfile(codex_path) or not os.access(codex_path, os.X_OK):
        raise InstallError("the Codex CLI %s is not an executable file; pass --codex-path" % codex_path)
    codex_home, home_source = args.codex_home, "--codex-home"
    if not codex_home and existing.get("codex_home"):
        codex_home, home_source = existing["codex_home"], "existing bridge config"
    if not codex_home and not existing and os.environ.get("CODEX_HOME"):
        codex_home, home_source = os.environ["CODEX_HOME"], "$CODEX_HOME"
    if not codex_home:
        codex_home, home_source = str(Path.home() / ".codex"), "Codex CLI default"
    # Always pinned, even the default, so a later ambient CODEX_HOME cannot switch the reconciliation account.
    codex_home = os.path.abspath(os.path.expanduser(codex_home))
    if any(ord(char) < 32 for char in codex_home):
        raise InstallError("--codex-home must not contain control characters")
    owned_directory(codex_home, "Codex home (pass --codex-home with the app-server's CODEX_HOME)")
    if not (socket_path + "/").startswith(codex_home.rstrip("/") + "/"):
        notes.append("the socket is outside the Codex home used for reconciliation (%s); make sure the app-server "
                     "behind it uses that home, or pass --codex-home" % codex_home)
    if os.path.lexists(socket_path):
        info = os.stat(socket_path) if os.path.exists(socket_path) else None
        if info is not None and not stat.S_ISSOCK(info.st_mode):
            raise InstallError("%s is not a Unix socket" % socket_path)
        if info is not None and info.st_uid != os.getuid():
            raise InstallError("%s belongs to another user; only a same-user app-server socket is supported" % socket_path)
    else:
        notes.append("the app-server socket does not exist yet; messages wait as known-unsent retries until it does")
    python = os.path.abspath(sys.executable)   # not resolved, so a python3.X upgrade keeps working
    script = home / "codex-local" / "codex_bridge.py"
    adapter = {"type": "exec", "argv": [python, str(script), "--config", str(config_path), "wake"]}
    old_adapter = (current or {}).get("wake_adapter")
    if old_adapter and old_adapter != adapter:
        raise InstallError("a different codex wake adapter is already installed; review it first")
    if not old_adapter and tailmsg_config.get("default_agent") == "codex" and \
            (tailmsg_config.get("wake_adapter") or tailmsg_config.get("on_message")):
        notes.append("codex messages were woken by the top-level adapter; the bridge takes over agents.codex and "
                     "the top-level adapter stays unchanged")
    unit = unit_contents(python, script, config_path, codex_path)
    # Pinned and unrelated settings survive upgrades (replies, timing, instructions, kind routing).
    try:
        config = merged_bridge_config(existing, home, state, home / "codex-local", thread_id, args.allow_replies,
                                      {"codex_path": codex_path, "codex_remote": args.codex_remote,
                                       "codex_home": codex_home})
    except RuntimeError as exc:
        raise InstallError(str(exc)) from exc
    notes += install_sources(SOURCE, home / "codex-local", write=False)[1]
    handler = config.get("excluded_kind_adapter")
    if handler and not (os.path.isfile(handler[0]) and os.access(handler[0], os.X_OK)):
        notes.append("excluded_kind_adapter %s is not an executable file; excluded kinds are not forwarded until "
                     "it is" % handler[0])
    tailmsg_config.setdefault("agents", {})
    if tailmsg_config["agents"] is None:
        tailmsg_config["agents"] = {}
    if tailmsg_config["agents"].get("codex") is None:
        tailmsg_config["agents"]["codex"] = {}
    tailmsg_config["agents"]["codex"]["wake_adapter"] = adapter
    return {"thread_id": thread_id, "home": home, "paths": paths, "state": state, "config": config,
            "tailmsg_config": tailmsg_config, "adapter": adapter, "old_adapter": old_adapter, "unit": unit,
            "codex_home_source": home_source, "notes": notes}


def install(args):
    os.umask(0o077)
    plan = plan_install(args)
    home, paths = plan["home"], plan["paths"]
    actions = [] if args.no_start else ["daemon-reload", "enable " + SERVICE, "restart " + SERVICE,
                                        "try-restart " + RECEIVER_SERVICE]
    if args.dry_run:
        print(json.dumps({
            "dry_run": True, "dispatcher_thread_id": plan["thread_id"], "tailmsg_home": str(home),
            "codex_remote": plan["config"]["codex_remote"], "codex_path": plan["config"]["codex_path"],
            "codex_home": plan["config"].get("codex_home"), "codex_home_source": plan["codex_home_source"],
            "would_copy": [str(paths["codex-local/" + name]) for name in FILES],
            "would_write": [str(paths[name]) for name in ("bridge-config.json", "tailmsg-config.json",
                                                          "service.systemd", "bridge-installation.json")],
            "codex_wake_adapter": plan["adapter"], "existing_codex_wake_adapter": plan["old_adapter"],
            "backup_directory": str(home / "backups" / (BACKUP_PREFIX + "<UTC timestamp>")),
            "would_run_systemctl_user": actions, "allow_replies": plan["config"]["allow_replies"],
            "dispatcher_instructions": plan["config"]["dispatcher_instructions"],
            "excluded_kinds": plan["config"].get("excluded_kinds", []),
            "unit": plan["unit"].decode("utf-8"), "notes": plan["notes"]}, ensure_ascii=False, indent=2))
        return 0
    before = None
    if not args.no_start:
        require_manager()
        before = service_state()
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    backup = home / "backups" / (BACKUP_PREFIX + stamp)
    backup.mkdir(mode=0o700, parents=True)
    manifest = {"service_manager": MANAGER, "service": SERVICE, "tailmsg_home": str(home),
                "service_state": before, "targets": []}
    for name in BACKUP_NAMES:
        path = paths[name]
        entry = {"path": str(path), "backup": None, "mode": None}
        if path.is_file():
            atomic(backup / name, path.read_bytes())
            entry.update(backup=name, mode=stat.S_IMODE(path.stat().st_mode))
        manifest["targets"].append(entry)
    atomic(backup / "manifest.json", (json.dumps(manifest, indent=2) + "\n").encode())
    hashes, _ = install_sources(SOURCE, home / "codex-local")
    plan["state"].mkdir(mode=0o700, parents=True, exist_ok=True)
    atomic(paths["bridge-config.json"], (json.dumps(plan["config"], ensure_ascii=False, indent=2) + "\n").encode())
    config_mode = stat.S_IMODE(paths["tailmsg-config.json"].stat().st_mode)
    atomic(paths["tailmsg-config.json"],
           (json.dumps(plan["tailmsg_config"], ensure_ascii=False, indent=2) + "\n").encode(), config_mode)
    atomic(paths["service.systemd"], plan["unit"], 0o644)
    receipt = {"dispatcher_thread_id": plan["thread_id"], "host_id": "local", "installed_at": stamp,
               "source": str(SOURCE), "files_sha256": hashes, "backup": str(backup), "service_manager": MANAGER,
               "service_label": SERVICE, "unit_path": str(paths["service.systemd"]),
               "allow_replies": plan["config"]["allow_replies"], "codex_remote": plan["config"]["codex_remote"],
               "codex_home": plan["config"].get("codex_home")}
    atomic(paths["bridge-installation.json"], (json.dumps(receipt, indent=2) + "\n").encode())
    result = {"installed": True, "started": False, "dispatcher_thread_id": plan["thread_id"],
              "backup": str(backup), "config": str(paths["bridge-config.json"]),
              "unit": str(paths["service.systemd"]), "notes": plan["notes"]}
    if args.no_start:
        # restart (not enable --now) so an already running bridge also loads upgraded code
        result["next"] = ("services untouched; apply yourself: systemctl --user daemon-reload && systemctl --user "
                          "enable %s && systemctl --user restart %s && systemctl --user try-restart %s"
                          % (SERVICE, SERVICE, RECEIVER_SERVICE))
    else:
        try:
            run_checked("daemon-reload")
            run_checked("enable", SERVICE)
            run_checked("restart", SERVICE)   # starts it, or reloads new code on an upgrade
        except InstallError as exc:
            raise InstallError("%s; files are installed, restore them with --rollback %s" % (exc, backup)) from exc
        result["started"] = True
        result["receiver_restarted"] = receiver_reload(result)
    print(json.dumps(result, ensure_ascii=False))
    return 0


def receiver_reload(result):
    """Reload the receiver's config only if it already runs under the user manager."""
    if systemctl("try-restart", RECEIVER_SERVICE).returncode == 0:
        return True
    result["notes"].append("%s was not restarted by the user manager; restart your receiver yourself so it loads "
                           "the codex wake adapter (the bridge also scans the inbox every few seconds)"
                           % RECEIVER_SERVICE)
    return False


def load_backup(args):
    """Validate a backup made by this installer for this data home before anything is touched."""
    home = resolve_home(args.tailmsg_home)
    backup = Path(args.rollback).expanduser().resolve()
    if backup.parent != home / "backups" or not backup.name.startswith(BACKUP_PREFIX) or not backup.is_dir():
        raise InstallError("not a Linux bridge backup of %s: %s" % (home, backup))
    manifest = read_json_object(backup / "manifest.json", "backup manifest")
    if manifest.get("service_manager") != MANAGER or manifest.get("tailmsg_home") != str(home):
        raise InstallError("the backup was not made by the Linux installer for %s" % home)
    targets = manifest.get("targets")
    expected = {name: str(path) for name, path in layout(home).items()}
    # Releases before the resident helper had one fewer source file. Preserve their
    # rollback manifests while still validating every path against the exact layout.
    legacy_names = tuple(name for name in BACKUP_NAMES if name != "codex-local/codex_resident.py")
    names = legacy_names if isinstance(targets, list) and len(targets) == len(legacy_names) else BACKUP_NAMES
    if not isinstance(targets, list) or len(targets) != len(names):
        raise InstallError("the backup manifest is incomplete")
    checked = []
    for name, entry in zip(names, targets):
        if not isinstance(entry, dict):
            raise InstallError("the backup manifest is malformed")
        path = Path(str(entry.get("path")))
        allowed = expected[name]
        if name == "service.systemd":   # the unit directory may differ by environment; the name may not
            allowed = str(path) if path.is_absolute() and path.name == SERVICE and \
                path.parent.parts[-2:] == ("systemd", "user") else None
        if str(path) != allowed or entry.get("backup") not in (None, name):
            raise InstallError("the backup manifest names an unexpected target: %s" % path)
        if entry.get("backup") is not None:
            regular_or_absent(backup / name)
            if not (backup / name).is_file():
                raise InstallError("the backup is missing %s" % name)
        regular_or_absent(path)
        if name == "service.systemd":
            require_unit_owner(path, home / "codex-bridge.json")
        mode = entry.get("mode")
        checked.append((path, entry.get("backup"), mode if isinstance(mode, int) and 0 <= mode <= 0o777 else 0o600))
    return home, backup, manifest, checked


def rollback(args):
    os.umask(0o077)
    home, backup, manifest, targets = load_backup(args)
    unit_path = next(path for path, name, _ in targets if path.name == SERVICE)
    if args.dry_run:
        print(json.dumps({
            "dry_run": True, "backup": str(backup),
            "would_restore": [str(path) for path, name, _ in targets if name is not None],
            "would_remove": [str(path) for path, name, _ in targets if name is None],
            "would_run_systemctl_user": [] if args.no_start else
            ["disable --now " + SERVICE, "daemon-reload", "restore recorded enable/start state",
             "try-restart " + RECEIVER_SERVICE],
            "queue_and_inbox_preserved": True}, ensure_ascii=False, indent=2))
        return 0
    current = None
    if not args.no_start:
        require_manager()
        current = service_state()
        if current["active"] and not unit_path.is_file():
            # A loaded daemon whose unit file is gone cannot be tied to this home; never change files under it.
            raise InstallError("%s is active but %s is missing, so it cannot be confirmed as this installation; "
                               "stop it yourself (systemctl --user stop %s), then roll back again; nothing was "
                               "restored" % (SERVICE, unit_path, SERVICE))
        if unit_path.is_file():
            # The daemon must be confirmed stopped before its files change; otherwise touch nothing.
            stopped = systemctl("disable", "--now", SERVICE)
            if stopped.returncode != 0 or systemctl("is-active", "--quiet", SERVICE).returncode == 0:
                raise InstallError("could not stop %s (%s); nothing was restored"
                                   % (SERVICE, (stopped.stderr or "").strip()[-200:] or "still active"))
    for path, name, mode in targets:
        if name is None:
            if path.is_file():
                path.unlink()
        else:
            atomic(path, (backup / name).read_bytes(), mode)
    result = {"rolled_back": True, "backup": str(backup), "queue_and_inbox_preserved": True, "notes": []}
    if args.no_start:
        result["next"] = ("services untouched; if the bridge is running, stop or restart it yourself: systemctl "
                          "--user daemon-reload && systemctl --user disable --now %s" % SERVICE)
    else:
        run_checked("daemon-reload")
        recorded = manifest.get("service_state")
        wanted = recorded if isinstance(recorded, dict) else current   # unknown after a --no-start install
        if unit_path.is_file():
            if wanted.get("enabled"):
                run_checked("enable", SERVICE)
            if wanted.get("active"):
                run_checked("start", SERVICE)
        result["service_state"] = {"enabled": bool(unit_path.is_file() and wanted.get("enabled")),
                                   "active": bool(unit_path.is_file() and wanted.get("active"))}
        result["receiver_restarted"] = receiver_reload(result)
    print(json.dumps(result, ensure_ascii=False))
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--thread-id", help="UUID of the existing Codex session used as the fixed dispatcher")
    parser.add_argument("--rollback", metavar="BACKUP", help="restore one installation backup (inbox and queue are kept)")
    parser.add_argument("--tailmsg-home", default="~/.tailmsg")
    parser.add_argument("--codex-remote", metavar="URL", help="unix:///absolute/socket of your running local app-server")
    parser.add_argument("--codex-path", help="Codex CLI providing `codex queue` (default: the installed value, "
                                             "else `codex` on PATH)")
    parser.add_argument("--codex-home", help="CODEX_HOME of that app-server (default: the installed value, else "
                                             "$CODEX_HOME on first install, else ~/.codex)")
    replies = parser.add_mutually_exclusive_group()
    replies.add_argument("--allow-replies", dest="allow_replies", action="store_true", default=None,
                         help="enable automatic replies (only with the user's authorization)")
    replies.add_argument("--no-allow-replies", dest="allow_replies", action="store_false",
                         help="disable automatic replies (default for new installs; upgrades keep the setting)")
    parser.add_argument("--no-start", action="store_true", help="write files only; never call systemctl")
    parser.add_argument("--dry-run", action="store_true", help="check and print the plan; write and run nothing")
    args = parser.parse_args(argv)
    if bool(args.rollback) == bool(args.thread_id):
        parser.error("provide exactly one of --thread-id or --rollback")
    try:
        return rollback(args) if args.rollback else install(args)
    except (InstallError, OSError) as exc:
        print("install_codex_bridge_linux: error: %s" % exc, file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
